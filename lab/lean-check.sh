#!/usr/bin/env bash
# Страж формальных моделей: все `lab/lean/VecDHT/*.lean` обязаны компилироваться, не содержать
# `sorry` и пользовательских аксиом, а их формулировки обязаны совпадать с заморозкой.
#
# С 2026-10-24 (`E-0093`) файл — тонкая обёртка над `lab/lean-check.py`: интерфейс и печатные ключи
# сохранены (`LEAN_FILE=`, `LEAN_TOTAL=`, `LEAN_ALL_OK=`), чтобы `lab/workspace-verify.sh`, `AGENTS.md`
# и шаблон PR не переписывать. Причина переезда измерена в PRE_FIX того же цикла: прежний скрипт
# считал `sorry` и `axiom` как `grep` по исходнику, и модель `axiom localBad : 1 = 2` +
# `theorem direct : 1 = 2 := localBad` проходила им как годная (выход 0), а ослабленная формулировка
# (`= 8` → `<= 8`) — как не отличающаяся от верной. Аксиомы доказательства видит только
# `#print axioms` по терминам, а формулировку — только дайджест, замороженный до прогона.
#
# Стоимость измерена на этом хосте: тёплый прогон пяти моделей 15,4 с, холодный ~63 с (числа
# прежнего прибора, четыре модели). Новый прибор компилирует каждую модель ОДИН раз — но дописанный
# источник со `#print axioms` по всем декларациям, то есть цена того же порядка: тёплый прогон
# `python lab/lean-check.py check --quiet` дал 14,7 с (`LEAN_MS_TOTAL=14451`) при тех же пяти моделях.
# Число печатается как цена, а не как гейт. Гейт стоит в `workspace-verify.sh` (один раз на закрытие
# цикла), а не перед каждой командой.
#
# Употребление:
#   bash lab/lean-check.sh [--quiet]              # проверка (то же, что и раньше)
#   bash lab/lean-check.sh freeze --cycle E-XXXX  # заморозить формулировки (делается на пре-регистрации)
#   bash lab/lean-check.sh selftest               # восемь посаженных дефектов + два контроля
set -uo pipefail
cd "$(dirname "$0")/.."
# Рабочая станция — Windows, и эти два каталога держат соответственно `lean` и линковщик. В CI
# (ubuntu-24.04, работа `formal.yml`) их не существует, и добавлять их в PATH бессмысленно, но
# безопасно; домашний элановский каталог добавляется только если он есть — так один и тот же скрипт
# заводится на обеих платформах, не теряя локальную настройку.
for p in "/c/Users/Admin/.elan/bin" "/c/Users/Admin/mingw64/bin" "$HOME/.elan/bin"; do
  [ -d "$p" ] && PATH="$p:$PATH"
done
export PATH
# Обратная совместимость: прежний вызов не имел подкоманды (`bash lab/lean-check.sh [--quiet]`),
# а `workspace-verify.sh` зовёт именно так. Подкоманда подставляется, если первым аргументом идёт
# флаг или аргументов нет вовсе.
case "${1:-}" in
  "") set -- check ;;
  --quiet) set -- check --quiet ;;
esac
exec python lab/lean-check.py "$@"
