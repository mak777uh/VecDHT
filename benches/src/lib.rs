//! Помощники замеров (§17.1: `benches/  P0-harness (recall/throughput/determinism), индекс, wire`).
//!
//! Почему это отдельный пакет с `harness = false`, а не тесты. Тест проверяет предикат — «X ≤
//! порога», и его результат бинарен. Замер обязан сообщить число и условия, при которых оно
//! получено: то же самое ядро на другом железе даёт другой результат, и «красный» тест в такой
//! ситуации врал бы о коде, а не о машине. Отсюда два правила, которые исполняются здесь букварно:
//!
//! * числа печатаются, а не сравниваются с Порогом Истины; пороги живут в тестах
//!   (`crates/*/tests/…`), где они проверяются на инвариантах, а не на скорости;
//! * время — только `--release`. В debug-профиле профиль железобетонно другой (инлайн исчезает,
//!   SIMD в `blake3` работает в том же режиме, но вызовы — нет), поэтому каждый вывод начинается
//!   с строки о профиле, а `cfg!(debug_assertions)` печатается как запрет использовать число.
//!
//! Объём работы по умолчанию мал: у мишеней стоит `test = false`, то есть `cargo test` их только
//! компилирует, а запускает их `cargo bench` — но и там прогон обязан быть коротким, иначе
//! полуночный релизный цикл превратится в часовой. Множитель — `VEC_DHT_BENCH_SCALE`; для гейтных
//! объёмов (§18.1: 51 200 записей, 200 запросов) есть `VEC_DHT_P0_FULL=1` в
//! `crates/vecdht-embed/tests/p0_harness.rs`.

#![forbid(unsafe_code)]

use std::time::Duration;

/// Кратность работы. Значение по умолчанию — 1, то есть «быстро и без обещаний»; 20 превращает
/// прогон в измерение, пригодное для переноса в спеку.
pub fn scale() -> usize {
    std::env::var("VEC_DHT_BENCH_SCALE")
        .ok()
        .and_then(|v| v.parse::<usize>().ok())
        .unwrap_or(1)
        .clamp(1, 1_000)
}

/// Профиль сборки — обязательная часть любого напечатанного числа.
pub fn profile() -> &'static str {
    if cfg!(debug_assertions) {
        "debug — числа НЕ пригодны для спеки, перезапусти с --release"
    } else {
        "release"
    }
}

pub fn header(name: &str, purpose: &str) {
    println!("== {name} == {purpose}");
    println!("профиль: {}; множитель VEC_DHT_BENCH_SCALE = {}", profile(), scale());
}

/// Одна строка результата: что мерили, сколько итераций, какое время и что из него следует.
pub fn rate(label: &str, count: usize, elapsed: Duration) {
    let secs = elapsed.as_secs_f64();
    let per_sec = if secs > 0.0 { count as f64 / secs } else { f64::INFINITY };
    println!(
        "{label}: {count} за {:.1} мс = {:.0}/с ({:.1} мкс на операцию)",
        secs * 1000.0,
        per_sec,
        if per_sec > 0.0 { 1e6 / per_sec } else { 0.0 }
    );
}

/// Число с единицей, которое не является скоростью (байты, МХеш/с, доли).
pub fn value(label: &str, v: f64, unit: &str) {
    println!("{label}: {v:.2} {unit}");
}

/// То, что в этом прогоне измерить нельзя. Печатается теми же словами, что и в тестах P0:
/// пропущенный гейт, названный «пропущенным», честнее числа, полученного не на том стенде.
pub fn not_measured(gate: &str, reason: &str) {
    println!("НЕ ИЗМЕРЕН: {gate} — {reason}");
}

/// Замешивание результата, чтобы компилятор не выкинул измеряемый цикл как мёртвый код.
/// Без `unsafe` и без `std::hint::black_box` (нестабильно на нашей версии rustc): аккумулятор
/// печатается в конце, поэтому «оптимизировано до нуля» было бы видно по абсурдному числу.
#[derive(Default)]
pub struct Sink(pub u64);

impl Sink {
    pub fn add(&mut self, v: u64) {
        self.0 = self.0.wrapping_add(v);
    }

    /// Вызывается после измерения: значение не влияет на время, но обязано быть прочитано.
    pub fn commit(&self, label: &str) {
        println!("{label}: контрольная сумма аккумулятора {} (признак, что цикл не вырезан)", self.0);
    }
}
